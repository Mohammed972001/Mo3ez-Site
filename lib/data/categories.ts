/** Category SEO record by slug (undefined → 404 the /c/ route). */
export function getCategorySeo(slug: string): CategorySeo | undefined {
  return categorySeo.find((c) => c.slug === slug);
}

/** Path helper for the dedicated category landing pages. */
export function categoryPath(slug: string): string {
  return `/c/${slug}`;
}

// Compile-time drift guard: every SEO record must map to a real catalog category.
const known = new Set(baseCategories.map((c) => c.slug));
for (const c of categorySeo) {
  if (!known.has(c.slug)) {
    throw new Error(`categorySeo slug "${c.slug}" has no matching catalog category`);
  }
}
